// ============================================================
// JAVASCRIPT ARRAYS
// ============================================================
//
// Array = ordered collection of values.
//
// Arrays are objects:
//
// typeof [] === "object"
//
// Arrays are:
// - Zero-indexed
// - Dynamic
// - Mutable
// - Able to contain mixed types
// ============================================================


// ============================================================
// CREATING ARRAYS
// ============================================================

const numbers = [10, 20, 30];

const mixed = [
    10,
    "hello",
    true,
    null,
    { name: "Shishir" }
];


// ============================================================
// ACCESS
// ============================================================

console.log(numbers[0]); // 10
console.log(numbers[2]); // 30

numbers[1] = 200;

console.log(numbers);
// [10, 200, 30]


// ============================================================
// LENGTH
// ============================================================

console.log(numbers.length); // 3


// ============================================================
// ADD / REMOVE FROM END
// ============================================================

numbers.push(40);

console.log(numbers);
// [10, 200, 30, 40]

numbers.pop();

console.log(numbers);
// [10, 200, 30]


// ============================================================
// ADD / REMOVE FROM BEGINNING
// ============================================================

numbers.unshift(5);

console.log(numbers);
// [5, 10, 200, 30]

numbers.shift();

console.log(numbers);
// [10, 200, 30]


// ============================================================
// SEARCH
// ============================================================

console.log(numbers.includes(200));
// true

console.log(numbers.indexOf(200));
// 1

console.log(numbers.indexOf(999));
// -1


// ============================================================
// SLICE
// ============================================================
// Does NOT mutate original.

const values = [10, 20, 30, 40];

console.log(values.slice(1, 3));
// [20, 30]

console.log(values);
// [10, 20, 30, 40]


// ============================================================
// SPLICE
// ============================================================
// Mutates original.
//
// splice(start, deleteCount, ...items)

values.splice(1, 2);

console.log(values);
// [10, 40]


// ============================================================
// MAP
// ============================================================

const nums = [1, 2, 3];

const doubled = nums.map(num => num * 2);

console.log(doubled);
// [2, 4, 6]


// ============================================================
// FILTER
// ============================================================

const even = nums.filter(num => num % 2 === 0);

console.log(even);
// [2]


// ============================================================
// REDUCE
// ============================================================

const sum = nums.reduce(
    (total, num) => total + num,
    0
);

console.log(sum);
// 6


// ============================================================
// FIND
// ============================================================

const users = [
    { id: 1, name: "A" },
    { id: 2, name: "B" }
];

const user = users.find(
    user => user.id === 2
);

console.log(user);
// { id: 2, name: "B" }


// ============================================================
// FIND INDEX
// ============================================================

console.log(
    users.findIndex(user => user.id === 2)
);
// 1


// ============================================================
// SOME / EVERY
// ============================================================

console.log(
    nums.some(num => num > 2)
);
// true

console.log(
    nums.every(num => num > 0)
);
// true


// ============================================================
// FOREACH
// ============================================================

nums.forEach((num, index) => {
    console.log(index, num);
});


// ============================================================
// SORT
// ============================================================

// Default sort is lexicographical.

const numbersToSort = [10, 2, 30];

numbersToSort.sort();

console.log(numbersToSort);
// [10, 2, 30]

// Numeric sorting:

numbersToSort.sort((a, b) => a - b);

console.log(numbersToSort);
// [2, 10, 30]


// ============================================================
// REVERSE
// ============================================================

numbersToSort.reverse();

console.log(numbersToSort);
// [30, 10, 2]


// ============================================================
// JOIN
// ============================================================

const words = ["Hello", "World"];

console.log(words.join(" "));
// "Hello World"


// ============================================================
// CONCAT
// ============================================================

const a = [1, 2];
const b = [3, 4];

const combined = a.concat(b);

console.log(combined);
// [1, 2, 3, 4]


// ============================================================
// SPREAD
// ============================================================

const original = [1, 2, 3];

const copy = [...original];

const extended = [...original, 4, 5];


// ============================================================
// DESTRUCTURING
// ============================================================

const [first, second, third] = [10, 20, 30];

console.log(first);  // 10
console.log(second); // 20
console.log(third);  // 30